frase = 'Curso em Vídeo Python'
print(frase[3]) # Mostra o caractere de índice 0 na variável frase
print(frase[9:20]) # Vai do caractere de índice 11 até 19 (ele não conta o 20)
print(frase[9:20:2]) # Vai do caractere de índice 11 até 19 pulando de dois em dois
print(frase[9::2]) # Vai do caractere de índice 11 até o final pulando de dois em dois
print(frase[::2]) # Vai do início até o final pulando de dois em dois
print(frase[9:]) # Mostra a string do décimo caractere até o final
print(frase[:5]) # Mostra a string frase até o quarto caractere
