n = input('Digite um número: ')
print(n.isnumeric())
# "isnumeric" vai te falar se o que foi digita é númerico ou pode ser convertido à númerico

f = input('Digite uma letra: ')
print(f.isalpha())
# "isalpha" vai te falar se é letra(s)

t = input('Digite algo: ')
print(t.isalnum())
# "isnum" vai te falar se é alfa númerico